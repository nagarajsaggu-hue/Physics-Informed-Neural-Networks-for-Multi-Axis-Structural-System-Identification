#!/bin/bash

echo "Updating Architectural Memory and Physics Constraints..."

# ==========================================
# 1. UPDATE README.md
# ==========================================
cat > README.md << 'EOF'
# Phase 1 - PINN System Identification

Identifying the stiffness and damping of a steel table from a single node's
displacement response across multiple axes (X, Y, Z), using a physics-informed neural network.

## Quick start

    source venv/bin/activate
    which python                          # must end in venv/bin/python

    # Select the target axis (X, Y, or Z) by uncommenting its block in config.yaml
    python -m pytest tests/ -v            
    python scripts/run_train.py --tag phase1_run
    python scripts/run_evaluate.py --tag phase1_run
    python scripts/run_plot.py --tag phase1_run

## Multi-Axis Flexibility

The model is direction-agnostic. The `config.yaml` file contains mutually exclusive blocks for the X, Y, and Z directions. 
* To switch directions, comment out the inactive blocks and uncomment the desired one. 
* Output JSONs, CSVs, and figures are automatically routed to specific subdirectories to strictly prevent data overwriting between cluster jobs.
* The Z-axis data utilizes a 500 Hz sampling rate (5000 samples), requiring a higher `num_domain` collocation density in the configuration.
EOF

# ==========================================
# 2. UPDATE AGENTS.md
# ==========================================
# Backup the old one just in case
[ -f AGENTS.md ] && cp AGENTS.md AGENTS.md.v2

cat > AGENTS.md << 'EOF'
# Phase 1 - PINN System Identification (Multi-Axis)

**Status: DIRECTION-AGNOSTIC ARCHITECTURE COMPLETE.** 

## What this project does

A steel table is shaken by a horizontal harmonic force in ANSYS. The displacement of one corner node is recorded across three spatial directions (X, Y, Z). A physics-informed neural network is trained to reproduce that displacement while simultaneously identifying the stiffness and damping of an equivalent single-degree-of-freedom system for the selected axis.

The codebase is completely direction-agnostic; axis selection is governed entirely by `config.yaml`.

## Key Learnings & Physics Constraints
* **Primary Axes (X, Y):** The 1-DOF PINN successfully extracts highly accurate stiffness and damping parameters because the horizontal external force directly drives these directions.
* **Parasitic Axes (Z):** The 1-DOF mathematical formulation collapses on the Z-axis. The external horizontal force (11,103 N) does not act in the Z-direction; the microscopic Z-displacement is merely a coupled structural vibration. Forcing a 1-DOF equation to balance a massive applied force against a parasitic vibration results in invalid parameters (negative least-squares stiffness, absurd PINN damping). This is a physical constraint of the 1-DOF equation, not a pipeline failure.

## Conventions

- **Direction Switching:** One configuration block (X, Y, or Z) must be active in `config.yaml` at a time. The active block strictly dictates the generalized mass, observation column, and output subdirectory.
- Submit a job, end the turn, come back later. Do not poll `squeue` in a loop.
- Do not edit files in `data/` - they come from ANSYS and are regenerated there.
EOF

echo "Architectural Memory Updated."
echo "Scanning for numerical results to update RESULTS.md..."

# ==========================================
# 3. DYNAMICALLY SCAN AND UPDATE RESULTS.md
# ==========================================

# Clear the old results section if it exists, then start fresh
sed -i '/## Phase 1.5 - Multi-Axis Evaluation Results/,$d' RESULTS.md
echo -e "\n## Phase 1.5 - Multi-Axis Evaluation Results\n" >> RESULTS.md

RESULTS_FOUND=0

# Loop through the axis output folders (X, Y, Z)
for axis_dir in outputs/phase1/*/; do
    if [ -d "$axis_dir" ]; then
        axis_name=$(basename "$axis_dir")
        # Find any comparison text files generated by the evaluate script
        for comp_file in "$axis_dir"comparison_*.txt; do
            if [ -f "$comp_file" ]; then
                echo "### Axis: $axis_name" >> RESULTS.md
                cat "$comp_file" >> RESULTS.md
                echo -e "\n---\n" >> RESULTS.md
                RESULTS_FOUND=1
            fi
        done
    fi
done

# Append the Z-axis physical conclusion to the bottom of the results
cat >> RESULTS.md << 'EOF'
### Z-Axis Conclusion (Physical Limitation)
The Z-axis training completed successfully, but produced invalid 1-DOF parameters (negative least-squares stiffness, massive PINN damping). This confirms that a 1-DOF formulation cannot extract parameters for a parasitic axis. The external horizontal force (11,103 N) does not directly drive the Z-axis, causing the mathematical residual to collapse under an invalid boundary assumption.
EOF

if [ $RESULTS_FOUND -eq 1 ]; then
    echo "Results successfully extracted and appended to RESULTS.md."
else
    echo "No output results found yet. Run this script again after executing the model."
fi